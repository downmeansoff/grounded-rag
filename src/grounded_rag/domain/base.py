"""Под что именно подогнан движок, живёт здесь и больше нигде.

Чанкер, эмбеддер, гибридный поиск, RRF, rerank и метрики к предметной области
отношения не имеют и знать о ней не должны. Знать о ней обязаны ровно три
места: чем разбирается исходный файл, что говорится модели, когда она пишет
контекст чанка, и что говорится ей же, когда она отвечает на вопрос. Профиль
это те три места, собранные в один объект и выбираемые переменной DOMAIN.

Документ снаружи выглядит одинаково у любого профиля: идентификатор, название,
части и свободный словарь метаданных. Словарь, а не набор колонок, потому что
у тендера это заказчик и НМЦК, у научной статьи автор и журнал, а общего поля
между ними нет. Метаданные едут в промпт контекстуализатора и в базу, но не в
полнотекстовый индекс: расширять генерируемую колонку tsv под произвольные
ключи значит пересобирать индекс при каждой смене профиля.

Идентификатор документа профиль назначает сам и отвечает за его уникальность
внутри корпуса: он же первичный ключ в базе и он же то, чем разметка замера
указывает, где лежит правильный ответ.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from pathlib import Path


@dataclass
class Part:
    """Часть документа: приложение к закупке, глава, отдельный файл."""

    name: str
    text: str
    ext: str = ""


@dataclass
class Document:
    doc_id: str
    title: str = ""
    source_path: str = ""
    meta: dict[str, str] = field(default_factory=dict)
    parts: list[Part] = field(default_factory=list)
    # Исходный файл целиком, как он лежит на диске. Нужен замеру: разметка
    # сверяется с документом до всякого чанкинга, и сверять её надо ровно с
    # оригиналом, а не с тем, что профиль сумел из него разобрать.
    raw: str = ""

    def part(self, name: str) -> Part | None:
        for part in self.parts:
            if part.name == name:
                return part
        return None


class DomainProfile(ABC):
    """Всё, что движок знает о предметной области корпуса."""

    # Имя профиля в переменной DOMAIN.
    name: str = ""
    # Как называть документ в цитате: «тендер 0312...», «документ readme».
    entity: str = "документ"
    # Чему посвящён корпус. Подставляется в промпт генерации ответа.
    corpus: str = "документам корпуса"
    # Версия промпта контекстуализации, часть ключа кэша. У каждого профиля
    # своя: контексты, написанные под тендерный промпт, к другому промпту
    # отношения не имеют, и подставлять их туда было бы враньём. Нумерация
    # тоже своя, потому что версии профилей меняются независимо.
    prompt_version: str = "1"
    # Ключ метаданных с именем владельца документа (у тендера это заказчик).
    # Из него берёт значения автофильтр по тексту запроса. Пустая строка -
    # профиль такого ключа не знает, и автофильтр молча ничего не подставляет:
    # у произвольного markdown из frontmatter владельца не достать.
    filter_key: str = ""

    @abstractmethod
    def load(self, docs_dir: Path) -> list[Document]:
        """Разбирает каталог в документы. Пустые документы не возвращает."""

    @property
    @abstractmethod
    def context_system(self) -> str:
        """Системный промпт для описания места чанка в документе."""

    @abstractmethod
    def context_prompt(self, doc: Document, part_name: str, head: str, text: str) -> str:
        """Пользовательский промпт туда же: метаданные, шапка документа, чанк."""

    @property
    def answer_system(self) -> str:
        """Системный промпт генерации.

        Общий для всех профилей: требование отвечать только по блокам, ставить
        номер источника и прямо отказываться - это и есть grounding, он от
        предметной области не зависит. Профиль меняет в нём одну строку.
        """
        return (
            f"Ты отвечаешь на вопросы по {self.corpus}. "
            "Используй только текст блоков ниже, помеченных [1], [2] и так далее. "
            "После каждого факта в ответе указывай номер источника в квадратных скобках. "
            'Если в блоках нет ответа на вопрос — прямо напиши "в найденных документах '
            'ответа нет", не добавляй факты из общих знаний и не угадывай.'
        )

    def citation(self, doc_id: str, part_name: str, chunk_index: int) -> str:
        return f"{self.entity} {doc_id}, {part_name}#{chunk_index}"
