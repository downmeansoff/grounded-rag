"""Ошибки, о которых знают сразу несколько слоёв.

Обе про одно: уже собранный индекс не соответствует коду, который к нему
пришёл. Размерность вектора это договор между моделью и колонкой в базе, и
нарушить его может любая из сторон: модель вернёт длину не ту, что объявлена,
или индекс окажется собран под прошлый бэкенд. Имена колонок это такой же
договор со схемой, и ломает его версия кода, а не пользователь.

Обе ошибки поднимаются до первой записи в базу. Иначе прогон падает где-то в
середине корпуса на сообщении Postgres, из которого не видно ни причины, ни
что делать дальше.
"""

from __future__ import annotations


class DimensionMismatch(RuntimeError):
    """Длина вектора не совпадает с той, под которую заведён индекс."""


class SchemaOutdated(RuntimeError):
    """Таблицы собраны прошлой версией схемы и под неё же названы колонки."""
