"""Отпечаток документа в индексе: по нему ingest решает, надо ли его трогать.

На четырнадцати документах переиндексация всего корпуса занимает минуту, и
вопроса нет. На архиве в тысячу закупок она занимает полчаса и повторяется при
каждом добавлении одной новой, поэтому неизменившиеся документы надо
пропускать.

Признак «не изменился» здесь не про дату файла и не про его размер. Дата
меняется от повторной выгрузки того же текста, а размер совпадает у разных
текстов. Считается отпечаток от того, что реально попадает в индекс: заголовок,
метаданные, имена частей и сами тексты.

Одного содержимого мало. Индекс зависит ещё и от того, чем его собирали, и
незаметная смена настроек хуже лишней работы: старые векторы остались бы лежать
рядом с новыми, поиск смешивал бы два разных пространства, и по выдаче это
никак не видно. Поэтому в отпечаток идут профиль, версия его промпта, модель
эмбеддингов с размерностью, размер чанка с перекрытием и признак
контекстуализации. Меняется любое из этого - меняются все отпечатки сразу, и
корпус переиндексируется целиком, как и должен.
"""

from __future__ import annotations

import hashlib

from grounded_rag.domain.base import Document

# Разделитель полей внутри отпечатка. Байт, которого не бывает в тексте: иначе
# заголовок "А" с метаданными "Б" и заголовок "А|Б" без метаданных дали бы одну
# и ту же строку и один отпечаток на два разных документа.
SEPARATOR = "\x00"


def index_key(
    doc: Document,
    *,
    profile_name: str,
    prompt_version: str,
    embedding_model: str,
    embedding_dim: int,
    chunk_size: int,
    chunk_overlap: int,
    contextual: bool,
) -> str:
    """sha256 от содержимого документа и настроек сборки индекса."""
    fields = [
        profile_name,
        prompt_version,
        embedding_model,
        str(embedding_dim),
        str(chunk_size),
        str(chunk_overlap),
        "contextual" if contextual else "plain",
        doc.doc_id,
        doc.title,
    ]
    for key in sorted(doc.meta):
        fields += [key, doc.meta[key]]
    for part in doc.parts:
        fields += [part.name, part.text]

    digest = hashlib.sha256(SEPARATOR.join(fields).encode("utf-8"))
    return digest.hexdigest()
